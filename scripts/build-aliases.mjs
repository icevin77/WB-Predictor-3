// Derives alias tables from the embedded database and writes lib/normalize.js.
//
//   node scripts/build-aliases.mjs
//
// Every row carries both a canonical name and the name as the paper wrote it
// (cell/cell_raw, marker/marker_raw, drug/drug_raw). Those pairs are a
// ready-made synonym list, so the alias table is derived rather than guessed.
// Hand-maintained entries live in EXTRA below and are merged on top.

import fs from 'node:fs';
import path from 'node:path';
import { loadDB, baseNorm } from '../eval/lib.mjs';

const OUT = path.join(import.meta.dirname, '..', 'lib', 'normalize.js');

// Equivalences the database cannot supply because no paper happened to write
// both forms. Gene symbol to common protein name, and the abbreviations that
// appear in queries rather than in captions.
const EXTRA = {
  marker: {
    'TP53': 'p53', 'CDKN1A': 'p21', 'CDKN1B': 'p27', 'MKI67': 'Ki-67',
    'BCL2': 'Bcl-2', 'BCL2L1': 'Bcl-xL', 'BAX': 'Bax', 'MCL1': 'Mcl-1',
    'CASP3': 'Caspase-3', 'CASP9': 'Caspase-9', 'CASP8': 'Caspase-8',
    'AKT1': 'AKT', 'MAPK1': 'ERK1/2', 'MAPK3': 'ERK1/2', 'MTOR': 'mTOR',
    'CDH1': 'E-cadherin', 'CDH2': 'N-cadherin', 'VIM': 'Vimentin',
    'MMP9': 'MMP-9', 'MMP2': 'MMP-2', 'CCND1': 'Cyclin D1',
    'H2AFX': 'γH2AX', 'H2AX': 'γH2AX', 'gammaH2AX': 'γH2AX',
    'ERBB2': 'HER2', 'NEU': 'HER2', 'PARP1': 'PARP', 'BECN1': 'Beclin-1',
    'MAP1LC3B': 'LC3B', 'SQSTM1': 'p62'
  },
  drug: {
    '5FU': '5-Fluorouracil', 'CDDP': 'Cisplatin', 'DOX': 'Doxorubicin',
    'ADR': 'Doxorubicin', 'TMZ': 'Temozolomide', 'PTX': 'paclitaxel',
    'CPT': 'Camptothecin', 'MTX': 'Methotrexate', 'ARAC': 'Cytarabine'
  },
  cell: {}
};

// Words that carry no identity and only block a match.
const CELL_NOISE = /\b(cells?|cell\s*line|human|cancer|carcinoma|tumou?r)\b/gi;

// Phospho-site suffixes: "p-STAT3 (Tyr705)" and "p-STAT3" are the same antibody
// target for retrieval purposes.
const SITE = /\(?\s*(?:p|phospho)?[-\s]?(?:ser|thr|tyr|s|t|y)\s?\d{1,4}(?:\s*\/\s*(?:ser|thr|tyr|s|t|y)?\s?\d{1,4})*\s*\)?|\(\s*(?:de)?phosphorylated\s*\)/gi;

function buildPairs(rows, canonKey, rawKey) {
  // raw spelling -> canonical, keeping the canonical that appears most often.
  const votes = new Map();
  for (const r of rows) {
    const canon = (r[canonKey] || '').trim();
    const raw = (r[rawKey] || '').trim();
    if (!canon || !raw) continue;
    for (const variant of [raw, canon]) {
      const k = baseNorm(variant);
      if (!k || k === baseNorm(canon)) continue;
      if (!votes.has(k)) votes.set(k, new Map());
      const m = votes.get(k);
      m.set(canon, (m.get(canon) || 0) + 1);
    }
  }
  const out = {};
  for (const [k, m] of votes) {
    const best = [...m.entries()].sort((a, b) => b[1] - a[1])[0][0];
    out[k] = baseNorm(best);
  }
  return out;
}

function main() {
  const rows = loadDB();
  const alias = {};
  for (const [canonKey, rawKey] of [['cell', 'cell_raw'], ['marker', 'marker_raw'], ['drug', 'drug_raw']]) {
    alias[canonKey] = buildPairs(rows, canonKey, rawKey);
  }
  // Hand-maintained entries win over derived ones.
  for (const kind of Object.keys(EXTRA)) {
    for (const [from, to] of Object.entries(EXTRA[kind])) {
      alias[kind][baseNorm(from)] = baseNorm(to);
    }
  }
  // Collapse chains (a -> b -> c becomes a -> c) and drop self-references.
  for (const kind of Object.keys(alias)) {
    for (const k of Object.keys(alias[kind])) {
      let v = alias[kind][k], hops = 0;
      while (alias[kind][v] && alias[kind][v] !== v && hops++ < 8) v = alias[kind][v];
      if (v === k) delete alias[kind][k];
      else alias[kind][k] = v;
    }
  }

  const counts = Object.fromEntries(Object.entries(alias).map(([k, v]) => [k, Object.keys(v).length]));
  const body = `// GENERATED by scripts/build-aliases.mjs — do not edit by hand.
// Alias tables derived from the database's own canonical/raw name pairs
// (${counts.cell} cell, ${counts.marker} marker, ${counts.drug} drug entries),
// plus the hand-maintained gene-symbol equivalences in that script.
//
// One definition used in both places: the browser loads it with a script tag
// and Node imports it for its side effect, and either way it lands on
// globalThis.WB_NORM — so the app and the evaluation match names identically.
globalThis.WB_NORM = (function () {
  'use strict';

  var ALIAS = ${JSON.stringify(alias, null, 2).replace(/\n/g, '\n  ')};

  var CELL_NOISE = ${CELL_NOISE.toString()};
  var SITE = ${SITE.toString()};

  // Lowercase, strip separators, and fold the phospho prefix so that
  // "phospho-AKT" and "p-AKT" land on the same key.
  function baseNorm(s) {
    return String(s == null ? '' : s)
      .toLowerCase()
      .replace(/phospho/g, 'p')
      .replace(/[-_\\s\\/()\\[\\].,:;]/g, '')
      .trim();
  }

  // Normalise then resolve through the alias table for the given field.
  function norm(s, kind) {
    var v = String(s == null ? '' : s);
    if (kind === 'cell') v = v.replace(CELL_NOISE, ' ');
    if (kind === 'marker') v = v.replace(SITE, ' ');
    var k = baseNorm(v);
    var table = ALIAS[kind];
    if (!table) return k;
    if (table[k]) return table[k];
    // "phospho-ERBB2" is the phospho form of a symbol the table knows as
    // ERBB2 -> HER2, so resolve the stem and put the prefix back.
    if (k.charAt(0) === 'p' && table[k.slice(1)]) return 'p' + table[k.slice(1)];
    return k;
  }

  // Two names match when they normalise equal, or when one contains the other
  // and the shorter is long enough that containment is not an accident.
  function matches(a, b, kind) {
    var x = norm(a, kind), y = norm(b, kind);
    if (!x || !y) return false;
    if (x === y) return true;
    var short = x.length < y.length ? x : y;
    var long = x.length < y.length ? y : x;
    return short.length >= 4 && long.indexOf(short) >= 0;
  }

  return { norm: norm, baseNorm: baseNorm, matches: matches, ALIAS: ALIAS };
}());
`;
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, body, 'utf8');
  console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
  console.log(`  cell ${counts.cell} · marker ${counts.marker} · drug ${counts.drug} alias entries`);
}

main();
