// Fits a confidence model on the eval results and writes lib/calibration.js.
//
//   node eval/fit-calibration.mjs
//
// This is the one piece of actual machine learning in the project, and it is
// deliberately small: L2-regularised logistic regression over a handful of
// features that are known before the answer is graded. It replaces the
// hand-chosen +-15 adjustments with numbers fitted to outcomes.
//
// What it predicts is not the direction — the model still does that. It
// predicts whether that direction is right, which is what a confidence number
// is supposed to mean.
//
// Honesty: five-fold cross-validation is reported, so the improvement quoted
// is on data the fit did not see. The shipped weights are then refit on all of
// it, which is standard and is why the CV figure is the one to believe.

import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './lib.mjs';

const DATA = path.join(ROOT, 'eval', 'data');
const OUT = path.join(ROOT, 'lib', 'calibration.js');

const FEATURES = [
  ['stated', r => (r.confidence || 0) / 100],
  ['hasExact', r => (r.dbExact > 0 ? 1 : 0)],
  ['exactCount', r => Math.min(5, r.dbExact || 0) / 5],
  ['hasAnalogous', r => (r.dbAnalogous > 0 ? 1 : 0)],
  ['condScore', r => (r.condScore == null ? 0.5 : r.condScore)],
  ['quality', r => (r.qualityMean == null ? 0.5 : r.qualityMean / 100)],
  ['tierMeasured', r => /DB direct|Direct literature|LINCS direct/.test(r.evidenceLevel || '') ? 1 : 0],
  ['tierInferred', r => /inference|No data/i.test(r.evidenceLevel || '') ? 1 : 0]
];

const sigmoid = z => 1 / (1 + Math.exp(-z));

function design(rows) {
  return rows.map(r => ({
    x: FEATURES.map(([, f]) => f(r)),
    y: r.predicted === r.truth ? 1 : 0
  }));
}

function fit(data, { lr = 0.3, epochs = 4000, l2 = 0.01 } = {}) {
  const d = FEATURES.length;
  let w = new Array(d).fill(0), b = 0;
  for (let e = 0; e < epochs; e++) {
    const gw = new Array(d).fill(0);
    let gb = 0;
    for (const { x, y } of data) {
      const p = sigmoid(x.reduce((s, v, i) => s + v * w[i], b));
      const err = p - y;
      for (let i = 0; i < d; i++) gw[i] += err * x[i];
      gb += err;
    }
    for (let i = 0; i < d; i++) w[i] -= lr * (gw[i] / data.length + l2 * w[i]);
    b -= lr * (gb / data.length);
  }
  return { w, b };
}

const predict = (m, x) => sigmoid(x.reduce((s, v, i) => s + v * m.w[i], m.b));

// Expected calibration error over five equal-width bins.
function ece(pairs) {
  let total = 0;
  for (let i = 0; i < 5; i++) {
    const lo = i / 5, hi = (i + 1) / 5;
    const g = pairs.filter(([p]) => p >= lo && (p < hi || (i === 4 && p <= 1)));
    if (!g.length) continue;
    const acc = g.reduce((a, [, y]) => a + y, 0) / g.length;
    const conf = g.reduce((a, [p]) => a + p, 0) / g.length;
    total += (g.length / pairs.length) * Math.abs(acc - conf);
  }
  return total;
}

function brier(pairs) {
  return pairs.reduce((a, [p, y]) => a + (p - y) ** 2, 0) / pairs.length;
}

function main() {
  const p = path.join(DATA, 'results.jsonl');
  if (!fs.existsSync(p)) { console.error('run eval/run-eval.mjs first'); process.exit(1); }
  const byId = new Map();
  for (const l of fs.readFileSync(p, 'utf8').split('\n')) {
    if (l.trim()) { const r = JSON.parse(l); if (!r.error && r.predicted) byId.set(r.id, r); }
  }
  const rows = [...byId.values()];
  if (rows.length < 60) {
    console.error(`only ${rows.length} scored results — too few to fit on. Run the full eval.`);
    process.exit(1);
  }
  const data = design(rows);

  // Five-fold CV, deterministic folds.
  const folds = 5;
  const held = [], base = [];
  for (let k = 0; k < folds; k++) {
    const test = data.filter((_, i) => i % folds === k);
    const train = data.filter((_, i) => i % folds !== k);
    const m = fit(train);
    test.forEach(({ x, y }) => held.push([predict(m, x), y]));
  }
  rows.forEach(r => base.push([(r.confidence || 0) / 100, r.predicted === r.truth ? 1 : 0]));

  console.log(`fitted on ${rows.length} scored results, ${FEATURES.length} features\n`);
  console.log('                       stated      fitted');
  console.log(`  calibration error   ${(ece(base) * 100).toFixed(1).padStart(6)}pt   ${(ece(held) * 100).toFixed(1).padStart(6)}pt   (cross-validated)`);
  console.log(`  Brier score         ${brier(base).toFixed(4).padStart(7)}   ${brier(held).toFixed(4).padStart(7)}   (lower is better)`);
  const better = ece(held) < ece(base);
  console.log(`\n  ${better ? 'The fitted confidence is better calibrated than the stated one.'
    : 'No improvement — keep the stated confidence and do not ship these weights.'}`);

  const model = fit(data);
  const weights = Object.fromEntries(FEATURES.map(([n], i) => [n, +model.w[i].toFixed(5)]));

  fs.writeFileSync(OUT, `// GENERATED by eval/fit-calibration.mjs — do not edit by hand.
// Logistic regression over features known before grading, fitted on
// ${rows.length} held-out cases. Cross-validated calibration error
// ${(ece(held) * 100).toFixed(1)}pt, against ${(ece(base) * 100).toFixed(1)}pt for the model's own stated confidence.
//
// Returns the probability that a prediction's direction is correct, which is
// what the displayed confidence is meant to be.
globalThis.WB_CALIBRATION = (function () {
  'use strict';
  var W = ${JSON.stringify(weights, null, 2).replace(/\n/g, '\n  ')};
  var B = ${model.b.toFixed(5)};

  function features(p) {
    var ev = p.evidenceLevel || '';
    return {
      stated: Math.max(0, Math.min(100, p.confidence || 0)) / 100,
      hasExact: p.dbExact > 0 ? 1 : 0,
      exactCount: Math.min(5, p.dbExact || 0) / 5,
      hasAnalogous: p.dbAnalogous > 0 ? 1 : 0,
      condScore: p.condScore == null ? 0.5 : p.condScore,
      quality: p.qualityMean == null ? 0.5 : p.qualityMean / 100,
      tierMeasured: /DB direct|Direct literature|LINCS direct/.test(ev) ? 1 : 0,
      tierInferred: /inference|No data/i.test(ev) ? 1 : 0
    };
  }

  // p: { confidence, evidenceLevel, dbExact, dbAnalogous, condScore, qualityMean }
  function calibrate(p) {
    var f = features(p), z = B;
    for (var k in W) if (Object.prototype.hasOwnProperty.call(W, k)) z += W[k] * (f[k] || 0);
    return Math.round(100 / (1 + Math.exp(-z)));
  }

  return { calibrate: calibrate, weights: W, bias: B };
}());
`, 'utf8');

  console.log(`\nweights:`);
  Object.entries(weights).sort((a, b) => Math.abs(b[1]) - Math.abs(a[1]))
    .forEach(([k, v]) => console.log(`  ${k.padEnd(14)} ${v >= 0 ? '+' : ''}${v}`));
  console.log(`\nwrote ${path.relative(ROOT, OUT)}`);
  if (!better) console.log('NOTE: not better than stated confidence — do not wire this in yet.');
}

main();
